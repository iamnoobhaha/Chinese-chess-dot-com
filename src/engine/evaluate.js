const MIRROR = new Int8Array(90)
for (let i = 0; i < 90; i++) MIRROR[i] = idx(9 - ((i / 9) | 0), i % 9)

export function evaluate(bd, turn) {
  let s = 0
  for (let i = 0; i < 90; i++) {
    const p = bd[i]
    if (!p) continue
    const t = typeOf(p)
    if (colorOf(p) === RED) s += VAL[t] + PST[t][i]
    else s -= VAL[t] + PST[t][MIRROR[i]]
  }
  return turn === RED ? s + 10 : -(s + 10)
}
